export type TKey = keyof Dict
export const DICTS: Record<Lang, Dict> = { en, nl }

export function translate(lang: Lang, key: TKey, vars?: Record<string, string | number>) {
  let s: string = DICTS[lang][key] ?? DICTS.en[key] ?? key
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(String(v))
  return s
}

export const LangContext = createContext<Lang>('en')
export function useT() {
  const lang = useContext(LangContext)
  return Object.assign((key: TKey, vars?: Record<string, string | number>) => translate(lang, key, vars), { lang })
}

/** Pick the language-specific field of a record, e.g. name_en / name_nl. */
export function L<T extends object>(obj: T | undefined, field: string, lang: Lang): string {
  if (!obj) return ''
  const o = obj as Record<string, unknown>
  const v = o[`${field}_${lang}`] ?? o[`${field}_en`] ?? o[field]
  return v == null ? '' : String(v)
}
